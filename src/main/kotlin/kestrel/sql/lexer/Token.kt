package kestrel.sql.lexer

enum class TokenType {
    Identifier, IntLiteral, RealLiteral, TextLiteral,
    Create, Table, Insert, Into, Values, Select, From, Where,
    Order, By, Asc, Desc, Limit, Offset, Delete, Update, Set, Drop, Truncate, Identity, Continue,
    Alter, Add, Column, Rename, To, Default,
    And, Or, Not, Null, True, False, Primary, Key, As,
    Index, On, Inner, Left, Right, Full, Cross, Outer, Join, Lateral, Group, Having, Over, Partition,
    Rows, Row, Range, Groups, Preceding, Following, Unbounded, Current, Exclude, Ties, Others,
    Begin, Commit, Rollback, Transaction, Explain, Savepoint, Release,
    Conflict, Nothing, Do, Returning,
    Trigger, Before, After, For, Each,
    Is, In, Between, Like, Case, When, Then, Else, End, Exists, View, Replace,
    Union, All, Intersect, Except, With, Recursive, Distinct,
    Cast, Cascade, Restrict, References, Foreign, Check, No, Action, Unique, Constraint,
    Sequence, Increment, Minvalue, Maxvalue, Start, Cycle, Restart,
    Merge, Using, Matched,
    Prepare, Execute, Deallocate,
    Temp, Temporary,
    Collate,
    Integer, Text, Boolean, Real, Decimal, Date,
    Equal, NotEqual, Less, LessEqual, Greater, GreaterEqual,
    Plus, Minus, Star, Slash, Dot,
    LeftParen, RightParen, Comma, Semicolon,
    /** `$1`, `$2`, ... - see [kestrel.sql.ast.ParameterExpression]. [Token.intValue] carries the 1-based index. */
    Parameter,
    EndOfInput
}

data class Token(
    val type: TokenType,
    val lexeme: String,
    val line: Int,
    val column: Int,
    val intValue: Long? = null,
    val realValue: Double? = null,
    val textValue: String? = null
)

